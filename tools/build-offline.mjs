/* Regenerate after changing deployable files; does not modify lesson HTML. */
import { createHash } from "node:crypto";
import { readFile, readdir, realpath, stat, writeFile } from "node:fs/promises";
import { extname, relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import vm from "node:vm";

export const projectRoot = fileURLToPath(new URL("../", import.meta.url));

export async function buildManifest(root = projectRoot) {
  root = await realpath(root);
  const inventory = JSON.parse(await readFile(resolve(root, "assets/inventory.json"), "utf8"));
  const paths = new Set([
    "index.html",
    "referinte/despre-editie.html",
    "offline.html",
    "manifest.webmanifest",
    "LICENSE.txt",
    "assets/fonts/literata/OFL.txt",
    "README.md",
    ...inventory.pages.map((page) => page.path),
  ]);
  const allowed = new Set([
    ".css",
    ".js",
    ".png",
    ".svg",
    ".jpg",
    ".jpeg",
    ".gif",
    ".mp3",
    ".woff2",
  ]);
  async function walk(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) await walk(path);
      else if (entry.isFile() && allowed.has(extname(path).toLowerCase()))
        paths.add(relative(root, path).split(sep).join("/"));
    }
  }
  await walk(resolve(root, "assets"));
  const hash = createHash("sha256");
  hash.update(await readFile(resolve(root, "sw.js")));
  const assets = [];
  for (const path of [...paths].sort()) {
    const full = await realpath(resolve(root, path));
    if (relative(root, full).startsWith("..") || !(await stat(full)).isFile())
      throw new Error(`Invalid offline asset: ${path}`);
    const bytes = await readFile(full);
    hash.update(path).update("\0").update(bytes).update("\0");
    assets.push({ url: path, bytes: bytes.length });
  }
  return {
    version: hash.digest("hex").slice(0, 20),
    totalBytes: assets.reduce((sum, asset) => sum + asset.bytes, 0),
    assets,
  };
}

async function main() {
  const manifest = await buildManifest();
  const target = resolve(projectRoot, "offline-assets.js");
  if (process.argv.includes("--check")) {
    const context = { self: {} };
    vm.runInNewContext(await readFile(target, "utf8"), context);
    if (JSON.stringify(context.self.NEBULA_OFFLINE) !== JSON.stringify(manifest))
      throw new Error(
        "Offline manifest is stale. Run node tools/build-offline.mjs after formatting.",
      );
    console.log("Offline manifest is current.");
  } else {
    await writeFile(
      target,
      `/* Generated by tools/build-offline.mjs; do not edit by hand. */\nself.NEBULA_OFFLINE = ${JSON.stringify(manifest, null, 2)};\n`,
    );
    console.log(
      `Offline package: ${manifest.assets.length} files, ${(manifest.totalBytes / 1_000_000).toFixed(1)} MB.`,
    );
  }
}
if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
